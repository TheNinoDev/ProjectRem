/** Strip everything that is not icon geometry. */
function bodyOf(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/<svg[\s\S]*?>/, "")
    .replace(/<\/svg>/, "")
    .trim();
}

// Rust raw string. SVGs are full of `"`, so use a delimiter that cannot
// collide: `r##"..."##`.
const rustRaw = (s) => `r##"` + s + `"##`;

async function fetchOne(name, file) {
  const res = await fetch(`${CDN}/${file}.svg`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return bodyOf(await res.text());
}

const chunks = [];
const failures = [];

for (const [ident, file] of Object.entries(ICONS)) {
  try {
    const body = await fetchOne(ident, file);
    chunks.push(`    ${ident} => ${rustRaw(body)},`);
  } catch (err) {
    failures.push(`${file} (${err.message})`);
  }
}

const header = `// @generated by tools/fetch-lucide.mjs - do not edit by hand.
//
// Icon geometry from Lucide v0.544.0 (https://lucide.dev), ISC licensed.
// Icons are 24x24, stroked with width 2, round caps and joins.

`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + "icons! {\n" + chunks.join("\n") + "\n}\n", "utf8");

console.log(`wrote ${chunks.length} icons to ${OUT}`);
if (failures.length) {
  console.error(`FAILED ${failures.length}:`);
  for (const f of failures) console.error("  " + f);
  process.exit(1);
}